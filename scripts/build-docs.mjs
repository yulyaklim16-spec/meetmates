const ROOT = process.cwd();
const OUT = join(ROOT, 'design-system/docs');
const CSS_DIR = join(ROOT, 'design-system/components');

// ── чтение системы: значения и правила приходят из неё, а не из текста ──
const TOKENS = readFileSync(join(ROOT, 'design-system/tokens.css'), 'utf8');
const tokenValue = (name) => {
  const m = TOKENS.match(new RegExp(`${name}:\\s*([^;]+);`));
  if (!m) return null;
  const v = m[1].trim();
  const ref = v.match(/^var\((--[a-z0-9-]+)\)$/);
  return ref ? tokenValue(ref[1]) : v;
};

const cssCache = new Map();
const cssOf = (file) => {
  if (!cssCache.has(file)) cssCache.set(file, readFileSync(join(CSS_DIR, file), 'utf8'));
  return cssCache.get(file);
};

// Значение свойства у селектора: правила проходятся по порядку, последнее
// выигрывает — как в самом каскаде. Селектор ищется в списке через запятую,
// потому что .mm-btn объявлен вместе с .mm-head-btn.
const prop = (file, selector, name) => {
  const css = cssOf(file).replace(/\/\*[\s\S]*?\*\//g, '');
  let found = null;
  for (const m of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const selectors = m[1].split(',').map((s) => s.trim());
    if (!selectors.includes(selector)) continue;
    for (const d of m[2].split(';')) {
      const [k, ...rest] = d.split(':');
      if (k && k.trim() === name) found = rest.join(':').trim();
    }
  }
  if (found === null) throw new Error(`${file}: у ${selector} нет свойства ${name} — страница отстала от компонента`);
  // Имя токена раскрывается, только если им задано всё свойство: в шорткате
  // (font: var(--weight-600) var(--text-14)/…) первый токен — не значение.
  const whole = found.match(/^var\((--[a-z0-9-]+)\)$/);
  return { raw: found, token: whole ? whole[1] : null, resolved: whole ? tokenValue(whole[1]) : null };
};

// ── карта компонентов витрины: имя → данные ──────────────────────────
const BY_NAME = new Map();
for (const g of GROUPS) for (const c of g.cases) BY_NAME.set(c.name, { ...c, group: g });

// Снимки в разметке витрины лежат путями от ui/ — страницы docs стоят
// в другом месте. Файл при этом один: копий снимков для документации не заводим.
const fixPaths = (html) => html
  .replace(/(src|srcset)="img\//g, '$1="../../ui/img/')
  .replace(/, img\//g, ', ../../ui/img/');

const pick = (name, label) => {
  const c = BY_NAME.get(name);
  if (!c) throw new Error(`в витрине нет компонента «${name}»`);
  const cell = c.cells.find((x) => x.label === label);
  if (!cell) throw new Error(`у «${name}» нет клетки «${label}»`);
  return fixPaths(cell.html);
};

