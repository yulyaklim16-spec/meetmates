//
// На каждый компонент — своя страница из четырёх частей: анатомия, варианты
// и размеры, когда употреблять, правило и антиправило. Плюс index.html —
// showcase всех компонентов — и why.html, где написано, откуда взялся
// визуальный язык.
//
// Три вещи, на которых держится честность этих страниц:
//
// 1. Компоненты живые и те же, что в продукте. Разметка приходит из
//    build-kit-pages.mjs — из тех же данных, что рисуют витрину, — а одета
//    она в ../index.css, то есть в саму систему. Копий кода здесь нет.
// 2. Размеры читаются из design-system/components/*.css при сборке.
//    Свойство, которого в файле нет, роняет сборку: страница не может
//    пообещать высоту, которой у компонента не стало.
// 3. Части анатомии проверяются по разметке демо. Названная часть, которой
//    в образце нет, тоже роняет сборку.
//
// Запуск: node scripts/build-docs.mjs

